export function getProvinceById(id: string): Province | undefined {
  return IRAN_PROVINCES.find((p) => p.id === id);
}

export function getAllProvinceNames(): string[] {
  return IRAN_PROVINCES.map((p) => p.name);
}

export function getCitiesByProvince(provinceName: string): string[] {
  const province = IRAN_PROVINCES.find((p) => p.name === provinceName);
  return province?.cities || [];
}
